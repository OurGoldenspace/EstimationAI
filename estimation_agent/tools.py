# TOOL 2 — find_similar_projects
# ══════════════════════════════════════════════════════════════════════════════

def find_similar_projects(
    project_type: str,
    area_sf: float,
    province: str = "NB",
    city: str = "",
    top_n: int = 3,
) -> dict:
    """
    Finds the most similar past AGCM projects using weighted scoring.
    Returns top N matches with similarity scores and key benchmarks.

    Args:
        project_type: Type of construction (canonical or free-text)
        area_sf:      Total project area in square feet
        province:     Province abbreviation (default "NB")
        city:         City name (optional, improves matching)
        top_n:        Number of results to return (default 3)

    Returns:
        dict with: matches (list), coverage_warning, avg_cost_per_sf
    """
    scored = []
    for p in _PROJECTS:
        score = _similarity_score(p, project_type, area_sf, province, city)
        scored.append((score, p))

    # Sort descending by score
    scored.sort(key=lambda x: x[0], reverse=True)
    top = scored[:top_n]

    matches = []
    for score, p in top:
        # Size ratio for context
        size_ratio = area_sf / p["area_sf"] if p["area_sf"] else 1.0
        size_diff_pct = round((size_ratio - 1) * 100, 1)

        matches.append({
            "estimate_number":  p["estimate_number"],
            "estimate_name":    p["estimate_name"],
            "project_type":     p["project_type"],
            "area_sf":          p["area_sf"],
            "area_diff_pct":    size_diff_pct,    # +ve = new project is larger
            "province":         p["province"],
            "city":             p["city"],
            "budget_year":      p["budget_year"],
            "estimate_price":   p["estimate_price"],
            "cost_per_sf":      p["cost_per_sf"],
            "margin_pct":       p["margin_pct"],
            "schedule_weeks":   p["schedule_weeks"],
            "contract_type":    p["contract_type"],
            "result":           p["result"],
            "similarity_score": score,
            "confidence":       _confidence_label(score),
        })

    # Aggregate avg $/SF from top matches (weighted by similarity score)
    total_weight = sum(s for s, _ in top)
    if total_weight > 0:
        avg_cost_per_sf = sum(
            s * p["cost_per_sf"] for s, p in top
        ) / total_weight
    else:
        avg_cost_per_sf = 0

    # Coverage warning if best score is low
    best_score = top[0][0] if top else 0
    coverage_warning = None
    if best_score < 30:
        coverage_warning = (
            f"Best match score is only {best_score}/100 — "
            f"no strong comparable exists in the AGCM database for this project type/size. "
            f"Estimate confidence is LOW. Consider using general Atlantic Canada benchmarks."
        )
    elif best_score < 55:
        coverage_warning = (
            f"Moderate match quality (score {best_score}/100). "
            f"Comparable projects differ in type or size. Treat as indicative only."
        )

    return {
        "matches": matches,
        "total_projects_in_database": len(_PROJECTS),
        "avg_cost_per_sf_weighted": round(avg_cost_per_sf, 2),
        "coverage_warning": coverage_warning,
        "query": {
            "project_type": _normalize_type(project_type),
            "area_sf": area_sf,
            "province": province,
            "city": city,
        },
    }


def _confidence_label(score: float) -> str:
    if score >= 70:
        return "HIGH"
    elif score >= 45:
        return "MEDIUM"
    elif score >= 25:
        return "LOW"
    else:
        return "VERY LOW"


