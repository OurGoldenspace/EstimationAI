# TOOL 3 — get_division_benchmarks
# ══════════════════════════════════════════════════════════════════════════════

def get_division_benchmarks(
    project_type: str,
    area_sf: float,
    province: str = "NB",
    comparable_estimate_numbers: Optional[list[str]] = None,
) -> dict:
    """
    Returns CSI division-level $/SF benchmarks for the new project,
    derived from the most similar past projects.

    If comparable_estimate_numbers are provided (from find_similar_projects),
    uses those projects' exact division data. Otherwise finds the best matches.

    Args:
        project_type:                  Type of construction
        area_sf:                       New project area in SF
        province:                      Province
        comparable_estimate_numbers:   List of estimate numbers to use as source (optional)

    Returns:
        dict with: divisions (list of CSI benchmarks), total_construction_cost, total_cost_per_sf
    """
    # Determine which projects to pull division data from
    if comparable_estimate_numbers:
        source_nums = set(comparable_estimate_numbers)
        source_divs = [d for d in _DIVISIONS if d["estimate_number"] in source_nums]
    else:
        # Find top 3 similar projects
        result = find_similar_projects(project_type, area_sf, province, top_n=3)
        source_nums = set(m["estimate_number"] for m in result["matches"])
        source_divs = [d for d in _DIVISIONS if d["estimate_number"] in source_nums]

    if not source_divs:
        return {
            "error": "No division data found for the selected comparable projects.",
            "divisions": [],
            "total_construction_cost": 0,
            "total_cost_per_sf": 0,
        }

    # Group by division code, compute weighted average $/SF
    from collections import defaultdict
    division_groups: dict[str, list] = defaultdict(list)
    for d in source_divs:
        division_groups[d["division_code"]].append(d)

    benchmarks = []
    total_cost_per_sf = 0.0

    for code in sorted(division_groups.keys()):
        entries = division_groups[code]
        div_name = entries[0]["division_name"]

        # Weighted average $/SF — weight by how similar area is to new project
        weights = []
        for e in entries:
            if e["area_sf"] and e["area_sf"] > 0:
                ratio = area_sf / e["area_sf"]
                w = 1 / (1 + abs(math.log(ratio)))  # closer = higher weight
            else:
                w = 0.5
            weights.append(w)

        total_w = sum(weights)
        if total_w > 0:
            avg_cost_per_sf = sum(
                e["cost_per_sf"] * w for e, w in zip(entries, weights)
            ) / total_w
            avg_pct = sum(
                e["pct_of_project"] * w for e, w in zip(entries, weights)
            ) / total_w
        else:
            avg_cost_per_sf = 0
            avg_pct = 0

        estimated_total = round(avg_cost_per_sf * area_sf, 2)

        # Min/max range across comparables for confidence bounds
        cpf_values = [e["cost_per_sf"] for e in entries if e["cost_per_sf"] > 0]
        range_low  = min(cpf_values) if cpf_values else 0
        range_high = max(cpf_values) if cpf_values else 0

        benchmarks.append({
            "division_code":        code,
            "division_name":        div_name,
            "cost_per_sf":          round(avg_cost_per_sf, 2),
            "estimated_total":      estimated_total,
            "pct_of_project":       round(avg_pct, 2),
            "range_low_per_sf":     round(range_low, 2),
            "range_high_per_sf":    round(range_high, 2),
            "source_project_count": len(entries),
            "comparable_projects":  [e["estimate_name"] for e in entries],
        })

        total_cost_per_sf += avg_cost_per_sf

    total_construction_cost = round(total_cost_per_sf * area_sf, 2)

    return {
        "divisions":                benchmarks,
        "total_construction_cost":  total_construction_cost,
        "total_cost_per_sf":        round(total_cost_per_sf, 2),
        "area_sf":                  area_sf,
        "source_projects":          list(source_nums),
        "division_count":           len(benchmarks),
    }


