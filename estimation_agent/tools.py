"""
tools.py
========
Four ADK tools for the AGCM Estimation Agent.
Loads real project data from projects.json and divisions.json
generated by setup_data.py.

Tools:
  1. validate_project_inputs      — checks what info was provided, decides if estimate is possible
  2. find_similar_projects        — finds past AGCM projects using weighted similarity scoring
  3. get_division_benchmarks      — returns $/SF by CSI division benchmarked to comparable projects
  4. calculate_estimate_total     — computes price, margin, category, schedule from benchmarks
"""

import os
import json
import math
from typing import Optional

# ─── DATA LOADING ──────────────────────────────────────────────────────────────

_DATA_DIR = os.path.join(os.path.dirname(__file__), "data")

def _load_projects() -> list[dict]:
    path = os.path.join(_DATA_DIR, "projects.json")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

def _load_divisions() -> list[dict]:
    path = os.path.join(_DATA_DIR, "divisions.json")
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)

# Load once at module import
_PROJECTS = _load_projects()
_DIVISIONS = _load_divisions()

